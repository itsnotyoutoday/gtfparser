// Command gtfdoc prints the markdown status table of tf's builtins for this
// build of the engine (docs/reference/Status.md):
//
//	go run ./cmd/gtfdoc > docs/reference/Status.md
//
// Which builtins are stubs comes from the engine itself (Interp.Placeholders);
// the capability each host-dependent builtin needs is listed below by hand.
package main

import (
	"fmt"
	"os"
	"sort"

	"github.com/itsnotyoutoday/gtfparser"
)

// needs maps a builtin ("/name" or "name()") to the optional host capability
// it depends on to do its whole job. Keep it sorted by capability.
var needs = map[string]string{
	// connections: the core keeps the world database, the host owns sockets
	"/connect": "WorldHost (ConnectHost for options)", "/dc": "WorldHost (SocketHost for -all)",
	"/fg": "WorldHost (FgHost for -q)", "/listsockets": "SocketHost",
	"is_connected()": "SocketHost", "is_open()": "SocketHost", "nactive()": "SocketHost",
	"idle()": "IdleHost (no argument), SocketHost (world)", "sidle()": "SocketHost",
	"fake_recv()": "WorldHost", "nread()": "WorldHost",
	"gmcp()": "WorldHost", "msdp()": "WorldHost", "atcp()": "WorldHost", "option102()": "WorldHost",
	// display and process state only the client has
	"/limit": "LimitHost", "/relimit": "LimitHost", "/unlimit": "LimitHost",
	"/reboot": "RebootHost", "/help": "HelpHost", "/core": "Notifier",
	"/beep": "Notifier", "/localecho": "Notifier", "/suspend": "Notifier", "/restrict": "Notifier",
	"keycode()": "KeyHost", "columns()": "TermHost", "lines()": "TermHost",
	"isatty()": "TermHost", "nmail()": "Notifier", "read()": "Notifier",
	"morepaused()": "MoreHost (optional)", "morescroll()": "MoreHost (optional)", "moresize()": "MoreHost (optional)",
	"winlines()": "WindowHost (optional)", "status_fields()": "StatusHost (optional)",
	"prompt()": "PromptHost (optional)",
	// basic Host: output and sending
	"/echo": "Host", "/send": "Host", "echo()": "Host", "send()": "Host",
}

func main() {
	in := gtfparser.New(gtfparser.Console(os.Stderr))
	stub := map[string]bool{}
	for _, n := range in.Placeholders() {
		stub[n] = true
	}
	var cmds, fns []string
	for _, c := range gtfparser.TFCommands() {
		cmds = append(cmds, "/"+c)
	}
	for _, f := range gtfparser.TFFunctions() {
		fns = append(fns, f+"()")
	}
	sort.Strings(cmds)
	sort.Strings(fns)
	fmt.Println("# Status of the builtins")
	fmt.Println()
	fmt.Println("Generated by `go run ./cmd/gtfdoc > docs/reference/Status.md`; do not edit by hand.")
	fmt.Println()
	fmt.Println("- **Implemented**: works in the engine on its own.")
	fmt.Println("- **Host-dependent**: implemented, but its full effect needs the embedding program to supply the named capability (see the host interfaces in `host.go`); without it the call degrades as described on its reference page.")
	fmt.Println("- **Not yet supported**: a stub; using it warns `not supported by this client` and fails.")
	var ni, nh, ns int
	section := func(title string, names []string) {
		fmt.Printf("\n## %s\n\n| Builtin | Status | Capability |\n|---|---|---|\n", title)
		for _, n := range names {
			st, cap := "Implemented", needs[n]
			switch {
			case stub[n]:
				st = "Not yet supported"
				ns++
			case cap != "":
				st = "Host-dependent"
				nh++
			default:
				ni++
			}
			if cap == "" {
				cap = "-"
			}
			fmt.Printf("| `%s` | %s | %s |\n", n, st, cap)
		}
	}
	section("Commands", cmds)
	section("Functions", fns)
	fmt.Printf("\nTotals: %d implemented, %d host-dependent, %d not yet supported (%d builtins).\n", ni, nh, ns, ni+nh+ns)
}
