#!/usr/bin/env python3
"""Generate pcre/props_gen.go: Unicode property tables taken from PCRE2 itself.

Builds scripts/pcre_props.c against a PCRE2 install (default
/opt/homebrew/opt/pcre2), asks it for the code point ranges of every general
category and script, and writes Go tables.  Plain \\p{Script} in PCRE2 >= 10.40
tests Script_Extensions, \\p{sc:Script} the Script property; both are emitted
(the latter only where it differs).

usage: pcre_genprops.py [--pcre2 DIR]
"""
import argparse, os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
CATS = "Lu Ll Lt Lm Lo Mn Mc Me Nd Nl No Pc Pd Ps Pe Pi Pf Po Sm Sc Sk So Zs Zl Zp Cc Cf Co Cn".split()


def dump(exe, names):
    out = subprocess.run([exe], input='\n'.join(names) + '\n', capture_output=True, text=True, check=True).stdout
    res, cur = {}, None
    for line in out.split('\n'):
        if line.startswith('='):
            cur = line[1:]; res[cur] = []
        elif line.startswith('!'):
            print('PCRE2 rejects', line[1:], file=sys.stderr)
        elif line:
            lo, hi = line.split()
            res[cur] += [int(lo, 16), int(hi, 16)]
    return res


def fmt(name, rs):
    body = ','.join('0x%x' % x for x in rs)
    return '\t"%s": {%s},\n' % (name, body)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--pcre2', default='/opt/homebrew/opt/pcre2')
    a = ap.parse_args()
    exe = os.path.join(tempfile.mkdtemp(), 'pcre_props')
    subprocess.check_call(['cc', '-O2', '-I' + a.pcre2 + '/include', '-L' + a.pcre2 + '/lib', '-lpcre2-8',
                           '-o', exe, os.path.join(HERE, 'pcre_props.c')])
    scripts = [l.strip() for l in open(os.path.join(HERE, 'pcre_props_scripts.txt')) if l.strip()]
    names = CATS + scripts + ['sc:' + s for s in scripts]
    t = dump(exe, names)
    ver = subprocess.run(['sh', '-c', 'ls -d %s/../../Cellar/pcre2/* 2>/dev/null | head -1' % a.pcre2],
                         capture_output=True, text=True).stdout.strip().split('/')[-1]
    o = ['// Code generated by scripts/pcre_genprops.py from PCRE2 %s; DO NOT EDIT.\n\n' % (ver or '10.47'),
         'package pcre\n\n// Ranges are lo,hi pairs of code points, keyed by normalised property name.\n\n',
         'var genCats = map[string][]rune{\n']
    for c in CATS:
        o.append(fmt(c.lower(), t[c]))
    o.append('}\n\n// genScx holds Script_Extensions (what plain \\p{Name} tests).\nvar genScx = map[string][]rune{\n')
    for s in sorted(scripts, key=lambda x: x.lower().replace('_', '')):
        o.append(fmt(s.lower().replace('_', ''), t[s]))
    o.append('}\n\n// genSc holds the Script property for scripts where it differs from genScx.\nvar genSc = map[string][]rune{\n')
    for s in sorted(scripts, key=lambda x: x.lower().replace('_', '')):
        if t['sc:' + s] != t[s]:
            o.append(fmt(s.lower().replace('_', ''), t['sc:' + s]))
    o.append('}\n')
    dst = os.path.join(HERE, '..', 'pcre', 'props_gen.go')
    open(dst, 'w').write(''.join(o))
    subprocess.check_call(['gofmt', '-w', dst])


main()
