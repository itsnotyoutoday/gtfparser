#!/usr/bin/env python3
"""Render a warncheck.py --json result as markdown, grouped by root cause (testdata/warnings/causes.tsv).

usage: warn_baseline.py RESULT.json > testdata/warnings/BASELINE.md
"""
import json, os, re, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import warncheck as wc

def clip(s, n=170):
    s = s.replace('|', '\\|').replace('`', "'")
    return s if len(s) <= n else s[:n - 3] + '...'

def main(path):
    res = json.load(open(path))
    causes = wc.load_causes()
    cat = wc.load_catalog()
    cnt = {}
    for r in res: cnt[r['status']] = cnt.get(r['status'], 0) + 1
    cls = {k: sum(1 for r in res if k in r['classes']) for k in ('body', 'context', 'missing', 'extra')}
    try:
        head = subprocess.run(['git', '-C', wc.ROOT, 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True).stdout.strip()
    except Exception:
        head = '?'
    out = []
    w = out.append
    n_cat = len(cat); n_test = sum(1 for e in cat.values() if e['status'] == 'testable')
    w('# Diagnostics baseline: gtfparser vs real tf\n')
    w('Generated by `scripts/warn_baseline.py` from `scripts/warncheck.py --json` (engine commit `%s`). ' % head)
    w('Regenerate: `go build -o /tmp/warn_gtfrun ./cmd/gtfrun && . scripts/env.sh && python3 scripts/warncheck.py --json /tmp/w.json --no-gate && python3 scripts/warn_baseline.py /tmp/w.json > testdata/warnings/BASELINE.md`.\n')
    w('## Summary\n')
    w('- catalog: **%d** entries, **%d** testable, %d untestable' % (n_cat, n_test, n_cat - n_test))
    w('- cases run: **%d**' % len(res))
    w('- status: ' + ', '.join('`%s` %d' % kv for kv in sorted(cnt.items(), key=lambda kv: -kv[1])))
    w('- mismatch classes (a case can have several): body %d, context %d, missing in gtfparser %d, extra in gtfparser %d' % (cls['body'], cls['context'], cls['missing'], cls['extra']))
    only_ctx = sum(1 for r in res if r['status'] == 'context')
    w('- body-only comparison (`--ignore-context`): **%d of %d** cases already match exactly' % (sum(1 for r in res if not any(c in r['classes'] for c in ('body', 'missing', 'extra'))), len(res)))
    crashes = [r['key'] for r in res if 'tf crashed' in r['notes']]
    w('- real tf crashed in: %s' % (', '.join(crashes) or 'none') + '. (Earlier probing found that real tf of this build crashes with signal 11 after printing `division by zero` inside a macro; that case is `expr.813` run at file level, so it is unaffected.)')
    w('')
    w('## Root causes, by priority\n')
    groups = {}
    for r in res:
        if r['status'] == 'OK': continue
        cl = [c for c in r['classes'] if c != 'context']
        if not cl and r['status'] != 'INVALID': continue
        cause, prio = wc.cause_of(causes, r['key'])
        groups.setdefault((int(prio), cause), []).append(r)
    ctxn = [r for r in res if 'context' in r['classes']]
    w('| priority | root cause | cases |')
    w('|---|---|---|')
    if ctxn: w('| 1 | context prefix differs | %d |' % len(ctxn))
    for (prio, cause), rs in sorted(groups.items()):
        w('| %d | %s | %d |' % (prio, cause, len(rs)))
    w('\n(priority 1 = most likely hit by a real script or user.)\n')
    w('## Context prefix format\n')
    w('Real tf prefixes errors with `% [<file>, line N: ][<command>[ -<opt>]: ]` (`eprefix()` in tfio.c). ')
    w('`<file>` is the file being `/load`ed, `lines N-M` for a backslash-continued command; `<command>` is the *innermost* ')
    w('running thing: the builtin\'s upper-case name (`DEF`, `EVAL`, `UNDEF`; `/test` and bare expressions show none), a macro\'s name, ')
    w('a function\'s name (`mod: `), or `#N` for an unnamed macro. Typed at the prompt there is no file part. Warnings add `Warning: ` after it. ')
    w('gtfparser builds the same prefix (`Interp.warn`); the table shows the probe cases of the context rules.\n')
    w('| case | real tf | gtfparser |')
    w('|---|---|---|')
    for k in ['ctx.file-line', 'ctx.macro', 'ctx.macro-nested', 'ctx.multiline', 'ctx.eval', 'ctx.trigger', 'ctx.hook', 'ctx.load-nested', 'ctx.option-suffix', 'ctx.function-name', 'ctx.builtin-in-macro', 'ctx.nonexistent-command', 'ctx.nonexistent-in-macro', 'ctx.typed', 'ctx.typed-macro', 'ctx.typed-builtin', 'ctx.typed-option']:
        r = next((x for x in res if x['key'] == k), None)
        if r: w('| %s | `%s` | `%s` |' % (k, clip(' | '.join(r['tf']) or '-', 110), clip(' | '.join(r['gtf']) or '-', 110)))
    w('')
    w('## Mismatch table by root cause\n')
    w('Text is the whole line after `% `; `<FILE>` stands for the script path and `<DIR>` for the scratch directory. A case with several lines is shown joined by ` // `.\n')
    for (prio, cause), rs in sorted(groups.items()):
        w('### P%d: %s (%d)\n' % (prio, cause, len(rs)))
        w('| key | status | real tf | gtfparser |')
        w('|---|---|---|---|')
        for r in rs:
            w('| %s | %s | `%s` | `%s` |' % (r['key'], r['status'], clip(' // '.join(r['tf']) or '(nothing)'), clip(' // '.join(r['gtf']) or '(nothing)')))
        w('')
    ok = [r['key'] for r in res if r['status'] == 'OK']
    w('## Exact matches\n')
    w(', '.join(ok) or 'none')
    w('')
    bodyok = [r['key'] for r in res if r['status'] == 'context']
    w('## Body already matches, only the context prefix differs (%d)\n' % len(bodyok))
    w(', '.join(bodyok))
    print('\n'.join(out))

if __name__ == '__main__':
    main(sys.argv[1])
