package gtfparser

import (
	"fmt"
	"strconv"
	"strings"
)

// Attr is a TinyFugue display attribute set: the same bit layout as the
// real client built with 256 colors, so values round-trip with its /list and
// attribute-string output. Attributes are data; rendering them is the
// client's job (see AttrString and LineResult).
type Attr uint32

const (
	AttrUnderline Attr = 0x00000001
	AttrReverse   Attr = 0x00000002
	AttrBold      Attr = 0x00000004
	AttrItalic    Attr = 0x00000008
	AttrHilite    Attr = 0x00000010 // expands to %hiliteattr when combined
	AttrNone      Attr = 0x00000020 // "n": matches/clears "no attributes"
	AttrExclusive Attr = 0x00000040 // "x": discard existing attributes first

	AttrFgColor Attr = 0x00000080 // flag: a foreground color is set
	AttrFgMask  Attr = 0x0000ff00 // the color number, shifted by 8
	AttrBgMask  Attr = 0x00ff0000 // the color number, shifted by 16
	AttrBgColor Attr = 0x80000000 // flag: a background color is set

	AttrNoActivity Attr = 0x01000000 // "A": does not count as activity
	AttrNoLog      Attr = 0x02000000 // "L": not logged
	AttrBell       Attr = 0x04000000 // "b"
	AttrGag        Attr = 0x08000000 // "g"
	AttrNoHistory  Attr = 0x10000000 // "G"
	AttrTFPrompt   Attr = 0x20000000 // the line is a prompt generated by tf
	AttrSrvPrompt  Attr = 0x40000000 // the line is a prompt from the server

	attrFgColors = AttrFgColor | AttrFgMask
	attrBgColors = AttrBgColor | AttrBgMask
	attrColors   = attrFgColors | attrBgColors
	attrSimple   = AttrUnderline | AttrReverse | AttrBold | AttrItalic
	// AttrDisplay is the set of attributes a terminal can render (tf's F_HWRITE).
	AttrDisplay = attrSimple | AttrHilite | attrColors
	attrEncode  = attrSimple | AttrHilite | AttrFgColor | AttrBgColor
)

// FgColor returns the foreground color number (valid if a.HasFg()).
func (a Attr) FgColor() int { return int(a&AttrFgMask) >> 8 }

// BgColor returns the background color number (valid if a.HasBg()).
func (a Attr) BgColor() int { return int(a&AttrBgMask) >> 16 }
func (a Attr) HasFg() bool  { return a&AttrFgColor != 0 }
func (a Attr) HasBg() bool  { return a&AttrBgColor != 0 }

// WithFg and WithBg return a with the given color numbers set.
func (a Attr) WithFg(c int) Attr { return a&^AttrFgMask | AttrFgColor | Attr(c)<<8 }
func (a Attr) WithBg(c int) Attr { return a&^AttrBgMask | AttrBgColor | Attr(c)<<16 }

// colorNames is tf's color table: 0-15 named, 16-231 the rgbRGB cube, 232-255
// the gray ramp.
var colorNames = func() []string {
	n := []string{"black", "red", "green", "yellow", "blue", "magenta", "cyan", "white",
		"gray", "brightred", "brightgreen", "brightyellow", "brightblue", "brightmagenta", "brightcyan", "brightwhite"}
	for r := 0; r < 6; r++ {
		for g := 0; g < 6; g++ {
			for b := 0; b < 6; b++ {
				n = append(n, fmt.Sprintf("rgb%d%d%d", r, g, b))
			}
		}
	}
	for i := 0; i < 24; i++ {
		n = append(n, "gray"+strconv.Itoa(i))
	}
	return n
}()

// colorListed reports whether a color appears in the "Valid values" list of
// an error message (tf elides the bulk of the table).
func colorListed(i int) bool {
	switch {
	case i <= 9, i == 15, i == 16, i == 231, i == 232, i == 255:
		return true
	}
	return false
}

// ColorName returns the name of color number n ("" if out of range).
func ColorName(n int) string {
	if n < 0 || n >= len(colorNames) {
		return ""
	}
	return colorNames[n]
}

// ColorNumber resolves a color name (case-insensitively) or number.
func ColorNumber(name string) (int, bool) {
	for i, c := range colorNames {
		if strings.EqualFold(name, c) {
			return i, true
		}
	}
	if name != "" && name[0] >= '0' && name[0] <= '9' {
		if n, err := strconv.Atoi(name); err == nil && n >= 0 && n < len(colorNames) {
			return n, true
		}
	}
	return 0, false
}

func invalidColor(kind, name string) error {
	var b strings.Builder
	b.WriteString("Valid values are: ")
	prefix := ""
	for i, c := range colorNames {
		if !colorListed(i) {
			prefix = " ... "
			continue
		}
		fmt.Fprintf(&b, "%s%s (%d)", prefix, c, i)
		prefix = ", "
	}
	return fmt.Errorf("Invalid %s value \"%s\".  %s", kind, name, b.String())
}

// AttrCtx carries the variables that give "h", "E", "W" and "I" their
// meaning (%hiliteattr, %error_attr, %warning_attr, %info_attr).
type AttrCtx struct{ Hilite, Error, Warning, Info Attr }

// Adj combines adj into base as tf does: "x" in adj discards base, colors in
// adj replace colors in base, everything else is OR'd. Hilite is expanded.
func (c AttrCtx) Adj(base, adj Attr) Attr {
	if base&AttrHilite != 0 {
		base &^= AttrHilite
		base |= c.Hilite
	}
	if adj&AttrHilite != 0 {
		adj &^= AttrHilite
		adj |= c.Hilite
	}
	if adj&AttrExclusive != 0 {
		return adj
	}
	if base&adj&AttrFgColor != 0 {
		base &^= AttrFgMask
	}
	if base&adj&AttrBgColor != 0 {
		base &^= AttrBgMask
	}
	return base | adj
}

// Parse reads an attribute list from s up to (not including) the delimiter
// byte (0: to the end), as /def -a and @{...} do. rest is s from the
// delimiter on.
func (c AttrCtx) Parse(s string, delim byte) (a Attr, rest string, err error) {
	i := 0
	for i < len(s) && (delim == 0 || s[i] != delim) {
		ch := s[i]
		i++
		switch ch {
		case ',':
		case 'n':
			a |= AttrNone
		case 'x':
			a |= AttrExclusive
		case 'G':
			a |= AttrNoHistory
		case 'L':
			a |= AttrNoLog
		case 'A':
			a |= AttrNoActivity
		case 'g':
			a |= AttrGag
		case 'u':
			a |= AttrUnderline
		case 'r':
			a |= AttrReverse
		case 'f', 'd': // flash and dim: accepted, ignored
		case 'i':
			a |= AttrItalic
		case 'B':
			a |= AttrBold
		case 'b':
			a |= AttrBell
		case 'h':
			a |= AttrHilite
		case 'E':
			a |= c.Error
		case 'W':
			a |= c.Warning
		case 'I':
			a |= c.Info
		case 'C':
			l := 0
			for i+l < len(s) && s[i+l] != ',' && (delim == 0 || s[i+l] != delim) {
				l++
			}
			var name string
			if i+l < len(s) && l < 16 {
				name = s[i : i+l]
				i += l
			} else {
				name = s[i:]
				i = len(s)
			}
			if strings.HasPrefix(name, "bg") {
				n, ok := ColorNumber(name[2:])
				if !ok {
					return a, s[i:], invalidColor("bgcolor", name[2:])
				}
				a = c.Adj(a, Attr(0).WithBg(n))
			} else {
				n, ok := ColorNumber(name)
				if !ok {
					return a, s[i:], invalidColor("color", name)
				}
				a = c.Adj(a, Attr(0).WithFg(n))
			}
		default:
			return a, s[i:], fmt.Errorf("invalid display attribute '%c'", ch)
		}
	}
	return a, s[i:], nil
}

// Format renders an attribute set in the form /list prints ("BuCred,Cbgblue").
func (a Attr) String() string {
	var b strings.Builder
	if a&AttrNone != 0 {
		b.WriteByte('n')
	}
	if a&AttrExclusive != 0 {
		b.WriteByte('x')
	}
	if a&AttrGag != 0 {
		b.WriteByte('g')
	}
	if a&AttrNoHistory != 0 {
		b.WriteByte('G')
	}
	if a&AttrNoLog != 0 {
		b.WriteByte('L')
	}
	if a&AttrNoActivity != 0 {
		b.WriteByte('A')
	}
	if a&AttrUnderline != 0 {
		b.WriteByte('u')
	}
	if a&AttrReverse != 0 {
		b.WriteByte('r')
	}
	if a&AttrItalic != 0 {
		b.WriteByte('i')
	}
	if a&AttrBold != 0 {
		b.WriteByte('B')
	}
	if a&AttrBell != 0 {
		b.WriteByte('b')
	}
	if a&AttrHilite != 0 {
		b.WriteByte('h')
	}
	if a.HasFg() {
		b.WriteString("C" + ColorName(a.FgColor()))
	}
	if a.HasBg() {
		if a.HasFg() {
			b.WriteByte(',')
		}
		b.WriteString("Cbg" + ColorName(a.BgColor()))
	}
	return b.String()
}

// attrMatch implements /list -a: does attr contain any of the attributes
// listed in sattr ("n" matches an empty set).
func attrMatch(sattr, attr Attr) bool {
	if sattr == AttrNone {
		return attr == 0
	}
	if sattr&^attrColors&attr != 0 {
		return true
	}
	if sattr&AttrFgColor != 0 && sattr&attrFgColors == attr&attrFgColors {
		return true
	}
	if sattr&AttrBgColor != 0 && sattr&attrBgColors == attr&attrBgColors {
		return true
	}
	return false
}

// ---------------------------------------------------------------- AttrString

// AttrString is text with display attributes: Attr applies to the whole line,
// and Chars (if non-nil, len(Text)+1 entries, one per byte plus a trailing
// one) adds per-byte attributes on top of it. This is what a client renders.
type AttrString struct {
	Text  string
	Attr  Attr
	Chars []Attr
}

// charAt returns the effective attributes of byte i.
func (s AttrString) charAt(ctx AttrCtx, i int) Attr {
	if s.Chars == nil {
		return s.Attr
	}
	return ctx.Adj(s.Attr, s.Chars[i])
}

// Spans returns the text split into runs of identical effective attributes
// (the form a renderer wants). The line-level Gag/NoLog/... flags appear on
// every span.
type Span struct {
	Text string
	Attr Attr
}

func (s AttrString) Spans(ctx AttrCtx) []Span {
	if s.Chars == nil || len(s.Text) == 0 {
		return []Span{{s.Text, s.Attr}}
	}
	var out []Span
	st := 0
	cur := s.charAt(ctx, 0)
	for i := 1; i <= len(s.Text); i++ {
		var a Attr
		if i < len(s.Text) {
			a = s.charAt(ctx, i)
		}
		if i == len(s.Text) || a != cur {
			out = append(out, Span{s.Text[st:i], cur})
			st, cur = i, a
		}
	}
	return out
}

// ensureChars allocates Chars filled with fill (check_charattrs).
func (s *AttrString) ensureChars(fill Attr) {
	if s.Chars != nil {
		return
	}
	s.Chars = make([]Attr, len(s.Text)+1)
	for i := range s.Chars {
		s.Chars[i] = fill
	}
}

// setAttr is tf's set_attr: record the attributes of the byte(s) just added
// to a line being built.
func (s *AttrString) setAttr(offset int, starting *Attr, cur Attr) {
	if s.Chars == nil {
		if len(s.Text) == 0 {
			*starting = cur
		} else if *starting != cur {
			s.ensureChars(*starting)
		}
	}
	if s.Chars != nil {
		for len(s.Chars) < len(s.Text)+1 {
			s.Chars = append(s.Chars, 0)
		}
		for ; offset < len(s.Text); offset++ {
			s.Chars[offset] = cur
		}
	}
}

func (s *AttrString) finish(starting, trailing Attr) {
	if s.Chars == nil {
		s.Attr |= starting
	} else {
		for len(s.Chars) < len(s.Text)+1 {
			s.Chars = append(s.Chars, 0)
		}
		s.Chars[len(s.Text)] = trailing
	}
}

// DecodeAttr converts embedded "@{attrs}" codes into attributes (tf's
// decode_attr and /echo -p); "@@" is a literal '@'. attrs is added to every
// character. offset skips that many bytes of the source.
func (c AttrCtx) DecodeAttr(src AttrString, attrs Attr, offset int) (AttrString, error) {
	var dst AttrString
	dst.Attr = c.Adj(src.Attr, attrs)
	starting := dst.Attr
	text := src.Text
	if offset > len(text) {
		offset = len(text)
	}
	for i := offset; i < len(text); i++ {
		if text[i] == '@' && i+1 < len(text) && text[i+1] == '{' {
			i += 2
			off := false
			if i < len(text) && text[i] == '~' {
				off = true
				i++
			}
			nw, rest, err := c.Parse(text[i:], '}')
			if err != nil {
				return AttrString{}, err
			}
			if rest == "" {
				return AttrString{}, fmt.Errorf("unmatched @{")
			}
			i = len(text) - len(rest)
			if nw&AttrBell != 0 && !off {
				dst.Attr |= AttrBell
			}
			nw &^= AttrBell
			if nw&AttrFgColor != 0 {
				attrs &^= AttrFgMask
			}
			if nw&AttrBgColor != 0 {
				attrs &^= AttrBgMask
			}
			if nw&AttrNone != 0 {
				attrs = 0
			}
			if off {
				attrs &^= nw
			} else {
				attrs |= nw
			}
			continue
		}
		var orig Attr
		if src.Chars != nil {
			orig = src.Chars[i]
		}
		dst.Text += text[i : i+1]
		dst.setAttr(len(dst.Text)-1, &starting, c.Adj(orig, attrs))
		if text[i] == '@' && i+1 < len(text) && text[i+1] == '@' {
			i++
		}
	}
	dst.finish(starting, attrs)
	return dst, nil
}

// EncodeAttr is the inverse of DecodeAttr: attributes become "@{...}" codes
// and '@' is doubled.
func (c AttrCtx) EncodeAttr(s AttrString, offset int) string {
	var b strings.Builder
	if offset > len(s.Text) {
		offset = len(s.Text)
	}
	if s.Chars == nil {
		if s.Attr != 0 {
			b.WriteString("@{" + s.Attr.String() + "}")
		}
		for i := offset; i < len(s.Text); i++ {
			b.WriteByte(s.Text[i])
			if s.Text[i] == '@' {
				b.WriteByte('@')
			}
		}
		if s.Attr != 0 {
			b.WriteString("@{n}")
		}
		return b.String()
	}
	var old, attrs Attr
	for i := offset; i < len(s.Text); i++ {
		attrs = c.Adj(s.Attr, s.Chars[i])
		if (attrs^old)&AttrDisplay != 0 {
			switch {
			case attrs&AttrDisplay == 0:
				b.WriteString("@{n}")
			case (old&^attrs)&attrEncode == 0:
				added := attrs &^ (old & attrSimple)
				if (attrs^old)&attrFgColors == 0 {
					added &^= attrFgColors
				}
				if (attrs^old)&attrBgColors == 0 {
					added &^= attrBgColors
				}
				b.WriteString("@{" + (added & AttrDisplay).String() + "}")
			default:
				b.WriteString("@{n" + (attrs & AttrDisplay).String() + "}")
			}
		}
		b.WriteByte(s.Text[i])
		if s.Text[i] == '@' {
			b.WriteByte('@')
		}
		old = attrs
	}
	if attrs&AttrDisplay != 0 {
		b.WriteString("@{n}")
	}
	return b.String()
}

func (c AttrCtx) attr2ansi(a Attr) string {
	if a&AttrHilite != 0 {
		a |= c.Hilite
	}
	var parts []string
	if a&AttrBold != 0 {
		parts = append(parts, "1")
	}
	if a&AttrItalic != 0 {
		parts = append(parts, "3")
	}
	if a&AttrUnderline != 0 {
		parts = append(parts, "4")
	}
	if a&AttrReverse != 0 {
		parts = append(parts, "7")
	}
	if a.HasFg() {
		n := a.FgColor()
		switch {
		case n < 8:
			parts = append(parts, strconv.Itoa(n+30))
		case n < 16:
			parts = append(parts, strconv.Itoa(n-8+90))
		default:
			parts = append(parts, "38;5;"+strconv.Itoa(n))
		}
	}
	if a.HasBg() {
		n := a.BgColor()
		switch {
		case n < 8:
			parts = append(parts, strconv.Itoa(n+40))
		case n < 16:
			parts = append(parts, strconv.Itoa(n-8+100))
		default:
			parts = append(parts, "48;5;"+strconv.Itoa(n))
		}
	}
	return strings.Join(parts, ";")
}

// EncodeAnsi renders attributes as ANSI escape sequences (tf's encode_ansi).
func (c AttrCtx) EncodeAnsi(s AttrString, offset int) string {
	var b strings.Builder
	if offset > len(s.Text) {
		offset = len(s.Text)
	}
	if s.Chars == nil {
		if s.Attr != 0 {
			b.WriteString("\x1b[" + c.attr2ansi(s.Attr) + "m")
		}
		b.WriteString(s.Text)
		if s.Attr != 0 {
			b.WriteString("\x1b[m")
		}
		return b.String()
	}
	var old, attrs Attr
	for i := offset; i < len(s.Text); i++ {
		attrs = c.Adj(s.Attr, s.Chars[i])
		if (attrs^old)&AttrDisplay != 0 {
			switch {
			case attrs&AttrDisplay == 0:
				b.WriteString("\x1b[m")
			case (old&^attrs)&attrEncode == 0:
				added := attrs &^ (old & attrSimple)
				if (attrs^old)&attrFgColors == 0 {
					added &^= attrFgColors
				}
				if (attrs^old)&attrBgColors == 0 {
					added &^= attrBgColors
				}
				b.WriteString("\x1b[" + c.attr2ansi(added&AttrDisplay) + "m")
			default:
				b.WriteString("\x1b[;" + c.attr2ansi(attrs&AttrDisplay) + "m")
			}
		}
		b.WriteByte(s.Text[i])
		old = attrs
	}
	if attrs&AttrDisplay != 0 {
		b.WriteString("\x1b[m")
	}
	return b.String()
}

// Emulation levels for DecodeAnsi (the %emulation variable).
const (
	EmulRaw = iota
	EmulPrint
	EmulAnsiStrip
	EmulAnsiAttr
	EmulDebug
)

// DecodeAnsi interprets ANSI attribute/color sequences in src (as the client
// does for text from a world, per %emulation): they become attributes; tabs
// expand when tabsize>0; other control codes are dropped. start is the
// attribute state at the start of the text; the state at the end is returned
// so a client can carry it across lines.
func (c AttrCtx) DecodeAnsi(src string, start Attr, emul int, tabsize int) (out AttrString, final Attr) {
	if emul == EmulRaw || emul == EmulDebug {
		return AttrString{Text: src, Attr: start}, start
	}
	attrs, starting := start, start
	colorstate := 0
	var dst AttrString
	rs := []byte(src)
	for i := 0; i < len(rs); i++ {
		ch := rs[i]
		csi := emul >= EmulAnsiStrip && (ch == 0x9b || (ch == 0x1b && i+1 < len(rs) && rs[i+1] == '['))
		if csi {
			if ch == 0x1b {
				i++
			}
			nw := attrs
			if i+1 >= len(rs) {
				break
			}
			for {
				i++
				n := 0
				neg := false
				if i < len(rs) && rs[i] == '-' {
					neg = true
					i++
				}
				st := i
				for i < len(rs) && rs[i] >= '0' && rs[i] <= '9' {
					n = n*10 + int(rs[i]-'0')
					i++
				}
				if i == st {
					n = -1
				} else if neg {
					n = -n
				}
				switch {
				case colorstate < 0:
				case colorstate%10 == 8:
					if n == 5 {
						colorstate++
					} else {
						colorstate = -1
					}
				case colorstate%10 == 9:
					if n < 0 || n > 255 {
						colorstate = -1
					} else {
						if colorstate/10 == 3 {
							nw = nw&^AttrFgMask | Attr(0).WithFg(n)
						} else {
							nw = nw&^AttrBgMask | Attr(0).WithBg(n)
						}
						colorstate = 0
					}
				case n == 0 || emul < EmulAnsiAttr:
					nw = 0
				case n >= 30 && n <= 37:
					nw = nw&^AttrFgMask | Attr(0).WithFg(n-30)
				case n >= 40 && n <= 47:
					nw = nw&^AttrBgMask | Attr(0).WithBg(n-40)
				case n >= 90 && n <= 97:
					nw = nw&^AttrFgMask | Attr(0).WithFg(n-90+8)
				case n >= 100 && n <= 107:
					nw = nw&^AttrBgMask | Attr(0).WithBg(n-100+8)
				case n == 38 || n == 48:
					colorstate = n
				default:
					switch n {
					case 1:
						nw |= AttrBold
					case 3:
						nw |= AttrItalic
					case 4:
						nw |= AttrUnderline
					case 7:
						nw |= AttrReverse
					case 21:
						nw &^= AttrBold
					case 22:
						nw &^= AttrBold
					case 23:
						nw &^= AttrItalic
					case 24:
						nw &^= AttrUnderline
					case 27:
						nw &^= AttrReverse
					case 39:
						nw &^= attrFgColors
					case 49:
						nw &^= attrBgColors
					}
				}
				if !(i < len(rs) && rs[i] == ';' && i+1 < len(rs)) {
					break
				}
			}
			if i >= len(rs) {
				break
			} else if rs[i] == '?' {
				i++
				if i >= len(rs) {
					break
				}
			} else if rs[i] == 'm' {
				attrs = nw
			}
		} else if emul >= EmulAnsiStrip && ch == 0x1b {
			i++
			if i >= len(rs) {
				break
			}
			if rs[i] == '(' || rs[i] == ')' || rs[i] == '#' {
				i++
				if i >= len(rs) {
					break
				}
			}
		} else if ch >= 0x20 && ch != 0x7f || ch == '\t' || ch >= 0x80 {
			orig := len(dst.Text)
			if ch == '\t' && tabsize > 0 {
				dst.Text += strings.Repeat(" ", tabsize-len(dst.Text)%tabsize)
			} else {
				dst.Text += string(ch)
			}
			dst.setAttr(orig, &starting, attrs)
		} else if ch == '\b' {
			if len(dst.Text) > 0 {
				dst.Text = dst.Text[:len(dst.Text)-1]
				if dst.Chars != nil {
					dst.Chars = dst.Chars[:len(dst.Text)+1]
				}
			}
		} else if ch == 7 {
			dst.Attr |= AttrBell
		}
	}
	dst.finish(starting, attrs)
	return dst, attrs
}

// attrCtx builds the AttrCtx for this interpreter from its variables.
func (in *Interp) attrCtx() AttrCtx {
	var c AttrCtx
	z := AttrCtx{}
	get := func(name string) Attr {
		v := in.globals[name].String()
		if v == "" {
			return 0
		}
		a, _, err := z.Parse(v, 0)
		if err != nil {
			return 0
		}
		return a
	}
	c.Hilite, c.Error, c.Warning, c.Info = get("hiliteattr"), get("error_attr"), get("warning_attr"), get("info_attr")
	return c
}

// ParseAttrs parses an attribute list using this interpreter's variables.
func (in *Interp) ParseAttrs(s string) (Attr, error) {
	a, _, err := in.attrCtx().Parse(s, 0)
	return a, err
}

// ---------------------------------------------------------------- echo with attributes

// AttrEchoHost is implemented by clients that can render attributes. Text
// echoed with attributes (/echo -a, -p, echo(), hook messages) reaches it as
// an AttrString; without it the plain text goes to Host.Echo, so a client
// that only shows text still works.
type AttrEchoHost interface{ EchoAttr(AttrString) }

// echoText is /echo and echo(): show text, optionally with attributes and
// with "@{...}" codes decoded.
func (in *Interp) echoText(text, attrs string, inline bool, dest string) Value {
	ctx := in.attrCtx()
	var a Attr
	if attrs != "" {
		var err error
		if a, _, err = ctx.Parse(attrs, 0); err != nil {
			in.warn("%v", err)
			return Int(0)
		}
	}
	if dest == "e" && attrs == "" {
		a = ctx.Error
	}
	if a == 0 && !inline {
		in.echo(text)
		return Int(1)
	}
	s := AttrString{Text: text}
	if inline {
		var err error
		if s, err = ctx.DecodeAttr(s, 0, 0); err != nil {
			in.warn("%v", err)
			return Int(0)
		}
	}
	s.Attr = ctx.Adj(s.Attr, a)
	in.echoAttr(s)
	return Int(1)
}

// echoAttr displays an attributed line on tfout (unless it is closed).
func (in *Interp) echoAttr(s AttrString) {
	for f := in.fr; f != nil; f = f.parent {
		if f.noOut {
			return
		}
	}
	if h, ok := in.Host.(AttrEchoHost); ok {
		h.EchoAttr(s)
		return
	}
	in.Host.Echo(s.Text)
}

// fnEchoAttr is echo(text [, attrs [, inline [, dest]]]).
func fnEchoAttr(in *Interp, a []Value) (Value, error) {
	inline := false
	if len(a) > 2 {
		var ok bool
		if inline, ok = in.flagArg(str(a, 2), "arg 3 (inline)"); !ok {
			return Int(0), nil
		}
	}
	dest := "o"
	if len(a) > 3 {
		dest = str(a, 3)
		if dest == "" {
			dest = "o"
		}
	}
	switch dest[0] {
	case 'o', 'e', 'a', 'w', 'r':
	default:
		in.warn("illegal destination '%c'", dest[0])
		return Int(0), nil
	}
	if dest[0] == 'w' && len(dest) > 1 && !in.worldKnown("ECHO", dest[1:]) {
		in.warn("No world %s", dest[1:])
		return Int(0), nil
	}
	return in.echoText(str(a, 0), str(a, 1), inline, dest[:1]), nil
}

// ---------------------------------------------------------------- functions

func init() {
	f := builtinFuncs
	f["strip_attr"] = func(in *Interp, a []Value) (Value, error) {
		// strings carry no attributes in this implementation, so stripping
		// them is the identity.
		return Str(str(a, 0)), nil
	}
	f["strcmpattr"] = func(in *Interp, a []Value) (Value, error) {
		// compares attributes (and text) of two strings; attributes are not
		// carried by values here, so this compares text.
		x, y := str(a, 0), str(a, 1)
		switch {
		case x < y:
			return Int(-1), nil
		case x > y:
			return Int(1), nil
		}
		return Int(0), nil
	}
	f["encode_attr"] = func(in *Interp, a []Value) (Value, error) {
		return Str(in.attrCtx().EncodeAttr(AttrString{Text: str(a, 0)}, 0)), nil
	}
	f["encode_ansi"] = func(in *Interp, a []Value) (Value, error) {
		return Str(in.attrCtx().EncodeAnsi(AttrString{Text: str(a, 0)}, 0)), nil
	}
	f["decode_ansi"] = func(in *Interp, a []Value) (Value, error) {
		out, _ := in.attrCtx().DecodeAnsi(str(a, 0), 0, EmulAnsiAttr, 0)
		return Str(out.Text), nil
	}
	f["decode_attr"] = func(in *Interp, a []Value) (Value, error) {
		ctx := in.attrCtx()
		var at Attr
		if len(a) > 1 {
			var err error
			if at, _, err = ctx.Parse(str(a, 1), 0); err != nil {
				in.warn("%v", err)
				return Str(""), nil
			}
		}
		inline := true
		if len(a) > 2 {
			var ok bool
			if inline, ok = in.flagArg(str(a, 2), "arg 3 (inline)"); !ok {
				return Str(""), nil
			}
		}
		if !inline {
			return Str(str(a, 0)), nil
		}
		out, err := ctx.DecodeAttr(AttrString{Text: str(a, 0)}, at, 0)
		if err != nil {
			in.warn("%v", err)
			return Str(""), nil
		}
		return Str(out.Text), nil
	}
}

// flagArg parses an enum_flag argument (off/on/0/1 ...) like tf's enum2int.
func (in *Interp) flagArg(s, what string) (val, ok bool) {
	switch strings.ToLower(s) {
	case "0", "off":
		return false, true
	case "1", "on":
		return true, true
	}
	in.warn("Invalid %s value \"%s\".  Valid values are: off (0), on (1)", what, s)
	return false, false
}
